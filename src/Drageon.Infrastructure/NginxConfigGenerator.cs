using System.Text;
using Drageon.Core;

namespace Drageon.Infrastructure;

public sealed class NginxConfigGenerator(IPortablePathService paths, JsonFileStore store)
    : ConfigGeneratorBase(paths, store), IConfigGenerator
{
    public string ComponentId => "nginx";
    public async Task<string> GenerateAsync(CancellationToken cancellationToken = default)
    {
        var version = await GetActiveVersionAsync(ComponentId, cancellationToken)
            ?? throw new InvalidOperationException("No active Nginx version.");
        var settings = await Store.ReadAsync<AppSettings>(Paths.Resolve("app", "config", "settings.json"), cancellationToken) ?? new();
        var nginxSettings = await VersionedComponentConfiguration.LoadAsync(
            Paths, Store, ComponentId, version, static () => new NginxSettings(), cancellationToken);
        var hosts = await new VirtualHostStore(Paths, Store).ReadAsync(cancellationToken: cancellationToken);
        var nginxRoot = Paths.Resolve("bin", ComponentId, version);
        var output = Path.Combine(VersionedComponentConfiguration.GetGeneratedDirectory(Paths, ComponentId, version), "nginx.conf");
        var logs = Paths.Resolve("app", "var", "logs", ComponentId);
        var temp = Paths.Resolve("app", "var", "tmp", ComponentId);
        Directory.CreateDirectory(logs);
        Directory.CreateDirectory(temp);
        Directory.CreateDirectory(Path.GetDirectoryName(output)!);
        var builder = new StringBuilder()
            .AppendLine("# Generated by Drageon. Changes will be overwritten.")
            .AppendLine("daemon off;")
            .AppendLine($"worker_processes {Math.Clamp(nginxSettings.WorkerProcesses, 1, 64)};")
            .AppendLine($"pid {Quote(Path.Combine(temp, "nginx.pid"))};")
            .AppendLine($"error_log stderr {SafeLogLevel(nginxSettings.LogLevel)};")
            .AppendLine($"error_log {Quote(Path.Combine(logs, "error.log"))} {SafeLogLevel(nginxSettings.LogLevel)};")
            .AppendLine($"events {{ worker_connections {Math.Clamp(nginxSettings.WorkerConnections, 128, 65535)}; }}")
            .AppendLine("http {")
            .AppendLine($"include {Quote(Path.Combine(nginxRoot, "conf", "mime.types"))};")
            .AppendLine("default_type application/octet-stream;")
            .AppendLine($"access_log {Quote(Path.Combine(logs, "access.log"))};")
            .AppendLine($"client_body_temp_path {Quote(Path.Combine(temp, "client_body"))};")
            .AppendLine($"fastcgi_temp_path {Quote(Path.Combine(temp, "fastcgi"))};")
            .AppendLine("client_max_body_size 0;")
            .AppendLine("index index.php index.html;");
        var phpMyAdmin = await GetActiveVersionAsync("phpmyadmin", cancellationToken);
        AppendServer("localhost", Paths.Resolve("www"), settings.HttpPort, true);
        foreach (var host in hosts.Where(host => host.Enabled))
            AppendServer(host.Host, host.DocumentRoot, host.Port ?? settings.HttpPort, false,
                host.GetServerConfiguration(ComponentId));
        if (!string.IsNullOrWhiteSpace(nginxSettings.CustomConfiguration))
            builder.AppendLine().AppendLine("# Custom Nginx configuration").AppendLine(nginxSettings.CustomConfiguration);
        builder.AppendLine("}");
        await File.WriteAllTextAsync(output, builder.ToString(), Utf8WithoutBom, cancellationToken);
        return output;

        void AppendFastCgi(string scriptFilename = "$document_root$fastcgi_script_name", string? scriptName = null)
        {
            builder.AppendLine($"include {Quote(Path.Combine(nginxRoot, "conf", "fastcgi_params"))};")
                .AppendLine($"fastcgi_pass 127.0.0.1:{settings.FastCgiPort};")
                .AppendLine($"fastcgi_param SCRIPT_FILENAME {scriptFilename};");
            if (scriptName is not null) builder.AppendLine($"fastcgi_param SCRIPT_NAME {scriptName};");
            builder
                .AppendLine("fastcgi_param HTTP_PROXY \"\";")
                .AppendLine("fastcgi_param HTTPS off;")
                .AppendLine("fastcgi_read_timeout 300s;");
        }
        void AppendServer(string host, string root, int port, bool isDefault, string additionalConfiguration = "")
        {
            builder.AppendLine("server {")
                .AppendLine($"listen {port}{(isDefault ? " default_server" : "")};")
                .AppendLine($"server_name {host};")
                .AppendLine($"root {Quote(root)};")
                .AppendLine("location ~ /\\.(?!well-known(?:/|$)) { deny all; }")
                .AppendLine("location / { try_files $uri $uri/ /index.php$is_args$args; }");
            if (isDefault && phpMyAdmin is not null)
            {
                var pmaRoot = Paths.Resolve("bin", "phpmyadmin", phpMyAdmin);
                var pmaScriptPath = "\"" + pmaRoot.Replace('\\', '/').Replace("\"", "\\\"") + "/$pma_script\"";
                builder.AppendLine("location = /phpmyadmin { return 301 /phpmyadmin/; }")
                    .AppendLine($"location ^~ /phpmyadmin/ {{ alias {Quote(pmaRoot + "/")};")
                    .AppendLine("location ~ /\\. { deny all; }")
                    .AppendLine("location ~* ^/phpmyadmin/(?<pma_script>.+\\.php)$ {");
                AppendFastCgi(pmaScriptPath, "/phpmyadmin/$pma_script");
                builder.AppendLine("} }");
            }
            builder.AppendLine("location ~* \\.php$ { try_files $uri =404;");
            AppendFastCgi();
            builder.AppendLine("}");
            if (!string.IsNullOrWhiteSpace(additionalConfiguration))
                foreach (var line in additionalConfiguration.Replace("\r\n", "\n", StringComparison.Ordinal).Replace('\r', '\n').Split('\n'))
                    builder.Append("    ").AppendLine(line);
            builder.AppendLine("}");
        }
    }

    internal static string Quote(string path) => "\"" + path.Replace('\\', '/').Replace("\"", "\\\"").Replace("$", "\\$") + "\"";
    private static string SafeLogLevel(string value) => value.ToLowerInvariant() is "debug" or "info" or "notice" or "warn" or "error" or "crit"
        ? value.ToLowerInvariant() : "warn";
}
